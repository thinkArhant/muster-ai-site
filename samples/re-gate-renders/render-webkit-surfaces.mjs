/* WebKit renders of the re-gate round's touched surfaces, one section at a
   time. QuickLook is the only WebKit route on this machine and it renders a
   whole document scaled to a fixed width, so a full page puts §4 and the
   footer at a few pixels tall — each surface is therefore isolated by hiding
   its neighbours rather than by cropping, which keeps every measurement the
   engine's own rather than a resample of one.

   Output lands in tests/artifacts/, which is ignored: these are evidence for
   one review, regenerated by running this file from the repo root.

     node samples/re-gate-renders/render-webkit-surfaces.mjs
*/

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
const ROOT = process.cwd();
const OUT = join(ROOT, "tests", "artifacts");
const html = readFileSync(join(ROOT, "index.html"), "utf8");
const shots = [
  ["s04", `#hero,#watch-it-ship,#the-insight,#shipped-with-muster,#get-started,body>footer{display:none!important}`],
  ["foot", `#hero,#watch-it-ship,#the-insight,#the-decisions,#shipped-with-muster,#get-started{display:none!important}`],
  ["s05", `#hero,#watch-it-ship,#the-insight,#the-decisions,#get-started,body>footer{display:none!important}`],
  ["head", `main{display:none!important}body>footer{display:none!important}`]
];
for (const [label, css] of shots) {
  const src = join(ROOT, `.wk-${label}.html`);
  writeFileSync(src, html.replace("</head>", `<style>:root{color-scheme:dark}${css}</style></head>`));
  const dir = join(OUT, `wk-${label}`);
  rmSync(dir, { recursive: true, force: true }); mkdirSync(dir, { recursive: true });
  execFileSync("qlmanage", ["-t", "-s", "1280", "-o", dir, src], { stdio: "pipe", timeout: 60000, killSignal: "SIGKILL" });
  const png = join(dir, `.wk-${label}.html.png`);
  if (!existsSync(png)) { console.log(label, "NO RENDER"); continue; }
  writeFileSync(join(OUT, `regate-webkit-${label}.png`), readFileSync(png));
  rmSync(dir, { recursive: true, force: true }); rmSync(src, { force: true });
  console.log(label, "ok");
}
